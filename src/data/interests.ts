export type InterestOption = (typeof interestOptions)[number];

export function loadInterests(): string[] {
  if (typeof window === "undefined") return [...DEFAULT_INTERESTS];
  try {
    const raw = localStorage.getItem(INTERESTS_KEY);
    if (!raw) return [...DEFAULT_INTERESTS];
    const parsed = JSON.parse(raw) as string[];
    if (!Array.isArray(parsed)) return [...DEFAULT_INTERESTS];
    return parsed.filter((t) => interestOptions.includes(t as InterestOption));
  } catch {
    return [...DEFAULT_INTERESTS];
  }
}

export function saveInterests(next: string[]) {
  localStorage.setItem(INTERESTS_KEY, JSON.stringify(next));
}
